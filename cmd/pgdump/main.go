// 从 PostgreSQL 库导出全量 DDL（不含数据），用于 PG 环境一键初始化。
//
// 用法（在 ops-go 目录下）：
//
//	go run ./cmd/pgdump -pg "<目标 PG DSN>" > sql/ops-go-pg.sql
//
// 结构由 GORM AutoMigrate 生成，本工具按 pg_catalog 还原成不依赖 pg_dump 版本的纯 SQL，
// 只适用于全新环境；已有数据的环境请勿执行其中的 DROP TABLE。
package main

import (
	"database/sql"
	"flag"
	"fmt"
	"os"
	"strings"
	"time"

	_ "github.com/jackc/pgx/v5/stdlib"
)

func main() {
	pgDSN := flag.String("pg", "", "PostgreSQL DSN（key=value 或 postgres:// 形式）")
	schema := flag.String("schema", "public", "导出哪个 schema")
	flag.Parse()
	if *pgDSN == "" {
		fmt.Fprintln(os.Stderr, "-pg 目标 DSN 不能为空")
		os.Exit(1)
	}
	db, err := sql.Open("pgx", *pgDSN)
	if err != nil {
		fatal("连接 PostgreSQL 失败", err)
	}
	defer db.Close()
	if err = db.Ping(); err != nil {
		fatal("连接 PostgreSQL 失败", err)
	}

	out := os.Stdout
	tables, err := listTables(db, *schema)
	if err != nil {
		fatal("读取表清单失败", err)
	}
	sequences, err := listSequences(db, *schema)
	if err != nil {
		fatal("读取序列清单失败", err)
	}
	fmt.Fprintf(out, "-- Ops-Go PostgreSQL 初始化 DDL（由 cmd/pgdump 导出，共 %d 张表）\n", len(tables))
	fmt.Fprintf(out, "-- 生成时间: %s\n", time.Now().Format("2006-01-02 15:04:05"))
	fmt.Fprintf(out, "-- 执行: psql -v ON_ERROR_STOP=1 -U <user> -d <dbname> -f ops-go-pg.sql\n")
	fmt.Fprintf(out, "-- 说明: 应用启动时 GORM AutoMigrate 也会建表，本文件供全新环境一键初始化\n\n")
	fmt.Fprintf(out, "SET client_min_messages = warning;\n\n")
	var pks, fks, cks []string

	for _, t := range tables {
		cols, err := listColumns(db, *schema, t)
		if err != nil {
			fatal("读取 "+t+" 列失败", err)
		}
		fmt.Fprintf(out, "DROP TABLE IF EXISTS %s CASCADE;\n", ident(t))
		// bigserial 列的 nextval 默认值依赖序列先存在，OWNED BY 则要求表已建好
		for _, c := range cols {
			if c.seq == "" {
				continue
			}
			def, ok := sequences[c.seq]
			if !ok {
				fatal(fmt.Sprintf("列 %s.%s 引用了未收录的序列 %s", t, c.name, c.seq), nil)
			}
			fmt.Fprintf(out, "CREATE SEQUENCE IF NOT EXISTS %s %s;\n", ident(c.seq), def)
		}
		var b strings.Builder
		fmt.Fprintf(&b, "CREATE TABLE %s (\n", ident(t))
		for i, c := range cols {
			b.WriteString("    ")
			b.WriteString(ident(c.name) + " " + c.typ)
			if c.identity != "" {
				if c.identity == "a" {
					b.WriteString(" GENERATED ALWAYS AS IDENTITY")
				} else {
					b.WriteString(" GENERATED BY DEFAULT AS IDENTITY")
				}
			} else if c.def != "" {
				b.WriteString(" DEFAULT " + c.def)
			}
			if c.notnull {
				b.WriteString(" NOT NULL")
			}
			if i < len(cols)-1 {
				b.WriteString(",")
			}
			b.WriteString("\n")
		}
		b.WriteString(");\n")
		fmt.Fprint(out, b.String())

		for _, c := range cols {
			if c.seq == "" {
				continue
			}
			fmt.Fprintf(out, "ALTER SEQUENCE %s OWNED BY %s.%s;\n", ident(c.seq), ident(t), ident(c.name))
			fmt.Fprintf(out, "ALTER TABLE %s ALTER COLUMN %s SET DEFAULT nextval('%s'::regclass);\n",
				ident(t), ident(c.name), c.seq)
		}

		if cmt, ok, err := tableComment(db, *schema, t); err != nil {
			fatal("读取 "+t+" 表注释失败", err)
		} else if ok {
			fmt.Fprintf(out, "COMMENT ON TABLE %s IS %s;\n", ident(t), quoteLit(cmt))
		}
		for _, c := range cols {
			if c.comment == "" {
				continue
			}
			fmt.Fprintf(out, "COMMENT ON COLUMN %s.%s IS %s;\n", ident(t), ident(c.name), quoteLit(c.comment))
		}

		constraints, err := listConstraints(db, *schema, t)
		if err != nil {
			fatal("读取 "+t+" 约束失败", err)
		}
		for _, def := range constraints {
			stmt := fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s %s;", ident(t), ident(def.name), def.body)
			// 主键/唯一先建，外键最后建：外键可能指向按表名排序时靠后的表
			switch def.kind {
			case "f":
				fks = append(fks, stmt)
			case "c":
				cks = append(cks, stmt)
			default:
				pks = append(pks, stmt)
			}
		}
		indexes, err := listIndexes(db, *schema, t)
		if err != nil {
			fatal("读取 "+t+" 索引失败", err)
		}
		for _, def := range indexes {
			fmt.Fprintln(out, def+";")
		}
		fmt.Fprintln(out)
	}
	fmt.Fprintln(out, "-- 主键 / 唯一约束")
	for _, s := range pks {
		fmt.Fprintln(out, s)
	}
	fmt.Fprintln(out, "\n-- 外键约束")
	for _, s := range fks {
		fmt.Fprintln(out, s)
	}
	if len(cks) > 0 {
		fmt.Fprintln(out, "\n-- CHECK 约束")
		for _, s := range cks {
			fmt.Fprintln(out, s)
		}
	}
}

type column struct {
	name     string
	typ      string
	def      string
	notnull  bool
	identity string
	seq      string // def 为 nextval(...) 时的序列名
	comment  string
}

type constraint struct {
	name string
	body string
	kind string // contype：p 主键 / f 外键 / u 唯一 / c check
}

// listSequences 返回序列名 → CREATE SEQUENCE 参数串
func listSequences(db *sql.DB, schema string) (map[string]string, error) {
	rows, err := db.Query(`SELECT c.relname, format_type(s.seqtypid, NULL), s.seqincrement, s.seqmin, s.seqmax, s.seqstart, s.seqcache, s.seqcycle
FROM pg_class c JOIN pg_namespace ns ON ns.oid = c.relnamespace JOIN pg_sequence s ON s.seqrelid = c.oid
WHERE ns.nspname = $1 ORDER BY c.relname`, schema)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := map[string]string{}
	for rows.Next() {
		var name, typ string
		var inc, mn, mx, st, ca int64
		var cycle bool
		if err = rows.Scan(&name, &typ, &inc, &mn, &mx, &st, &ca, &cycle); err != nil {
			return nil, err
		}
		cyc := "NO CYCLE"
		if cycle {
			cyc = "CYCLE"
		}
		out[name] = fmt.Sprintf("AS %s INCREMENT BY %d MINVALUE %d MAXVALUE %d START WITH %d CACHE %d %s",
			typ, inc, mn, mx, st, ca, cyc)
	}
	return out, rows.Err()
}

func listTables(db *sql.DB, schema string) ([]string, error) {
	rows, err := db.Query(`SELECT c.relname FROM pg_class c JOIN pg_namespace ns ON ns.oid = c.relnamespace
WHERE ns.nspname = $1 AND c.relkind = 'r' AND c.relpersistence = 'p' ORDER BY c.relname`, schema)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []string
	for rows.Next() {
		var t string
		if err = rows.Scan(&t); err != nil {
			return nil, err
		}
		out = append(out, t)
	}
	return out, rows.Err()
}

func listColumns(db *sql.DB, schema, table string) ([]column, error) {
	rows, err := db.Query(`SELECT a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
       a.attidentity, COALESCE(pg_get_expr(d.adbin, d.adrelid), ''), COALESCE(col_description(a.attrelid, a.attnum), '')
FROM pg_attribute a
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
JOIN pg_class c ON c.oid = a.attrelid
JOIN pg_namespace ns ON ns.oid = c.relnamespace
WHERE ns.nspname = $1 AND c.relname = $2 AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attnum`, schema, table)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []column
	for rows.Next() {
		var c column
		if err = rows.Scan(&c.name, &c.typ, &c.notnull, &c.identity, &c.def, &c.comment); err != nil {
			return nil, err
		}
		// identity 列的 nextval 默认值由 IDENTITY 子句表达，避免重复
		if c.identity != "" {
			c.def = ""
		}
		// bigserial 列：默认值依赖序列，序列名单独记录以便提前 CREATE SEQUENCE
		if rest, ok := strings.CutPrefix(c.def, "nextval('"); ok {
			if end := strings.Index(rest, "'"); end >= 0 && strings.Contains(c.def, "::regclass") {
				c.seq = rest[:end]
				c.def = ""
			}
		}
		out = append(out, c)
	}
	return out, rows.Err()
}

func listConstraints(db *sql.DB, schema, table string) ([]constraint, error) {
	rows, err := db.Query(`SELECT con.conname, con.contype::text, pg_get_constraintdef(con.oid)
FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid
JOIN pg_namespace ns ON ns.oid = c.relnamespace
WHERE ns.nspname = $1 AND c.relname = $2 ORDER BY con.conname`, schema, table)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []constraint
	for rows.Next() {
		var k constraint
		if err = rows.Scan(&k.name, &k.kind, &k.body); err != nil {
			return nil, err
		}
		out = append(out, k)
	}
	return out, rows.Err()
}

// 约束自带的索引不重复导出
func listIndexes(db *sql.DB, schema, table string) ([]string, error) {
	rows, err := db.Query(`SELECT i.indexdef FROM pg_indexes i
JOIN pg_class c ON c.relname = i.tablename AND c.relnamespace = (SELECT oid FROM pg_namespace WHERE nspname = $1)
LEFT JOIN pg_constraint con ON con.conindid = (SELECT oid FROM pg_class WHERE relname = i.indexname)
WHERE i.schemaname = $1 AND i.tablename = $2 AND con.oid IS NULL ORDER BY i.indexname`, schema, table)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []string
	for rows.Next() {
		var s string
		if err = rows.Scan(&s); err != nil {
			return nil, err
		}
		out = append(out, s)
	}
	return out, rows.Err()
}

func tableComment(db *sql.DB, schema, table string) (string, bool, error) {
	var cmt sql.NullString
	err := db.QueryRow(`SELECT obj_description(c.oid) FROM pg_class c JOIN pg_namespace ns ON ns.oid = c.relnamespace
WHERE ns.nspname = $1 AND c.relname = $2`, schema, table).Scan(&cmt)
	if err == sql.ErrNoRows {
		return "", false, nil
	}
	if err != nil {
		return "", false, err
	}
	return cmt.String, cmt.Valid && cmt.String != "", nil
}

func ident(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `""`) + `"`
}

func quoteLit(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

func fatal(msg string, err error) {
	fmt.Fprintf(os.Stderr, "%s: %v\n", msg, err)
	os.Exit(1)
}
